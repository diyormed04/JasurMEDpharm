// ==================== NOTIFICATIONS ====================
let notifications = JSON.parse(localStorage.getItem('jasurmed_notifications')) || [];

function pushNotification(role, email, title, body, orderId) {
    const notif = { id: Date.now(), role, email, title, body, orderId, read: false, time: new Date().toISOString() };
    notifications.unshift(notif);
    localStorage.setItem('jasurmed_notifications', JSON.stringify(notifications));
    renderNotifBell();
}

function renderNotifBell() {
    const bell = document.getElementById('notifBellBadge');
    if (!bell) return;
    const unread = notifications.filter(n => !n.read && (n.role === currentUser?.role || n.role === null)).length;
    if (unread > 0) {
        bell.classList.remove('hidden');
    } else {
        bell.classList.add('hidden');
    }
}

function toggleNotifPanel() {
    const existing = document.getElementById('notifPanel');
    if (existing) { existing.remove(); return; }
    const panel = document.createElement('div');
    panel.id = 'notifPanel';
    panel.className = 'notif-panel';
    const userNotifs = notifications.filter(n => n.role === currentUser?.role || n.role === null);
    panel.innerHTML = userNotifs.length === 0 ? '<div class="p-4 text-center text-gray-400 text-sm">Bildirishnomalar yo\'q</div>' : userNotifs.map(n => `
        <div class="notif-item ${n.read ? '' : 'unread'} cursor-pointer" onclick="markNotifRead(${n.id}); openOrderChat(${n.orderId})">
            <p class="text-sm font-medium dark:text-white">${n.title}</p>
            <p class="text-xs text-gray-400">${n.body}</p>
            <p class="text-xs text-gray-300 mt-1">${n.time.slice(11,16)}</p>
        </div>
    `).join('');
    document.getElementById('notifBellWrap').appendChild(panel);
}

function markNotifRead(id) {
    const notif = notifications.find(n => n.id === id);
    if (notif) notif.read = true;
    localStorage.setItem('jasurmed_notifications', JSON.stringify(notifications));
    renderNotifBell();
    const panel = document.getElementById('notifPanel');
    if (panel) panel.remove();
}


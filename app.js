function addToGuestCart(medId) {
    const med = medicines.find(m => m.id === medId);
    if (!med || med.stock === 0) return;
    const existing = cart.find(item => item.id === medId);
    if (existing) {
        if (existing.quantity < med.stock) existing.quantity++;
        else { showNotification("Omborda yetarli emas!", 'warning'); return; }
    } else {
        cart.push({ ...med, quantity: 1 });
    }
    updateGuestCartBadge();
    showNotification(translations[currentLang].addToCart + " ✓", 'success');
}

function updateGuestCartBadge() {
    const badge = document.getElementById('guestCartBadge');
    if (cart.length > 0) {
        badge.textContent = cart.length;
        badge.classList.remove('hidden');
    } else {
        badge.classList.add('hidden');
    }
}


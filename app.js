function sendBrowserNotification(title, body) {
    if ('Notification' in window && Notification.permission === 'granted') {
        new Notification(title, { body, icon: 'https://cdn-icons-png.flaticon.com/512/4320/4320337.png' });
    }
}

function showNotification(message, type = 'info') {
    const colors = { success: 'bg-success', danger: 'bg-danger', warning: 'bg-warning', info: 'bg-primary' };
    const notif = document.createElement('div');
    notif.className = `notification ${colors[type] || colors.info}`;
    notif.innerHTML = `<i class="fas fa-${type === 'success' ? 'check' : type === 'danger' ? 'times' : type === 'warning' ? 'exclamation' : 'info'}-circle mr-2"></i>${message}`;
    document.body.appendChild(notif);
    setTimeout(() => { notif.style.opacity = '0'; notif.style.transform = 'translateX(100%)'; setTimeout(() => notif.remove(), 300); }, 3000);
}

function closeModal(e) {
    if (e && e.target !== document.getElementById('modal')) return;
    document.getElementById('modal').classList.remove('show');
    document.getElementById('modalBody').className = 'modal-content p-6 dark:bg-gray-800';
}

function buildCategoryOptionsHtml(selected, withAll) {
    const t = translations[currentLang];
    const cats = [
        { id: 'all', label: t.all },
        { id: 'painkillers', label: t.painkillers },
        { id: 'antibiotics', label: t.antibiotics },
        { id: 'vitamins', label: t.vitamins },
        { id: 'cold', label: t.cold },
        { id: 'heart', label: t.heart },
        { id: 'diabetes', label: t.diabetes }
    ];
    return cats.filter(c => withAll || c.id !== 'all').map(c => `<option value="${c.id}" ${selected === c.id ? 'selected' : ''}>${c.label}</option>`).join('');
}


function saveMedicine(medId) {
    const nameLotin = document.getElementById('medNameLotin').value;
    const nameKril = document.getElementById('medNameKril').value;
    const price = parseInt(document.getElementById('medPrice').value) || 0;
    const stock = parseInt(document.getElementById('medStock').value) || 0;
    const category = document.getElementById('medCat').value;
    const prescription = document.getElementById('medPrescription').checked;
    if (!nameLotin || !nameKril) { showNotification("Barcha maydonlarni to'ldiring!", 'warning'); return; }
    if (medId) {
        const med = medicines.find(m => m.id === medId);
        med.name = { lotin: nameLotin, kril: nameKril };
        med.price = price; med.stock = stock; med.category = category; med.prescription = prescription;
    } else {
        medicines.push({
            id: Date.now(), name: { lotin: nameLotin, kril: nameKril }, category, price, stock, prescription,
            image: "💊", manufacturer: "Jasur Med", expiry: "2027-12",
            description: { lotin: "Yangi dori", kril: "Янги дори" }
        });
    }
    saveData(); closeModal(); renderPage();
    showNotification(translations[currentLang].save + " ✓", 'success');
}

